import { OrderStatus } from '../types/order';

export const VALID_ORDER_TRANSITIONS: Record<OrderStatus, OrderStatus[]> = {
  DRAFT: ['SUBMITTED', 'CANCELLED'],
  SUBMITTED: ['AWAITING_PAYMENT', 'AWAITING_REVIEW', 'CANCELLED', 'ON_HOLD', 'PENDING_RELEASE'],
  AWAITING_PAYMENT: ['READY_FOR_PRINT', 'AWAITING_REVIEW', 'PENDING_RELEASE', 'CANCELLED', 'ON_HOLD', 'FAILED_REQUIRES_SUPPORT'],
  AWAITING_REVIEW: ['READY_FOR_PRINT', 'PENDING_RELEASE', 'CANCELLED', 'ON_HOLD', 'FAILED_REQUIRES_SUPPORT'],
  READY_FOR_PRINT: ['IN_PROGRESS', 'PENDING_AGENT_SPOOL', 'ON_HOLD', 'CANCEL_REQUESTED', 'CANCELLED'],
  IN_PROGRESS: ['READY_FOR_COLLECTION', 'PRINT_FAILED', 'PRINT_UNCONFIRMED', 'ON_HOLD', 'FAILED_REQUIRES_SUPPORT'],
  READY_FOR_COLLECTION: ['COLLECTED', 'ON_HOLD'],
  COLLECTED: [], // Terminal success
  PENDING_RELEASE: ['READY_FOR_PRINT', 'IN_PROGRESS', 'ON_HOLD', 'CANCELLED'],
  PENDING_AGENT_SPOOL: ['READY_FOR_PRINT', 'IN_PROGRESS', 'ON_HOLD', 'CANCELLED'],
  PRINT_FAILED: ['READY_FOR_PRINT', 'IN_PROGRESS', 'ON_HOLD', 'CANCELLED', 'FAILED_REQUIRES_SUPPORT'],
  PRINT_UNCONFIRMED: ['READY_FOR_PRINT', 'IN_PROGRESS', 'READY_FOR_COLLECTION', 'ON_HOLD', 'CANCELLED', 'FAILED_REQUIRES_SUPPORT'],
  CANCEL_REQUESTED: ['CANCELLED', 'IN_PROGRESS', 'ON_HOLD'],
  CANCELLED: [], // Terminal cancellation
  ON_HOLD: ['READY_FOR_PRINT', 'IN_PROGRESS', 'AWAITING_REVIEW', 'CANCELLED'],
  FAILED_REQUIRES_SUPPORT: ['AWAITING_REVIEW', 'CANCELLED', 'ON_HOLD'],
};

export function canTransitionOrder(current: OrderStatus, next: OrderStatus): boolean {
  return VALID_ORDER_TRANSITIONS[current]?.includes(next) ?? false;
}

export function validateOrderTransition(current: OrderStatus, next: OrderStatus): void {
  if (!canTransitionOrder(current, next)) {
    throw new Error(`Illegal order transition from ${current} to ${next}`);
  }
}
